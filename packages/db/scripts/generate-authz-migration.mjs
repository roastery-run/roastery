/**
 * Emits the roles/permissions/plans seed as a migration.
 *
 * Generated from seed-authz.ts rather than hand-written, so the data the
 * authorization test validates against and the data the database actually
 * holds cannot drift apart.
 *
 * Idempotent (ON CONFLICT DO UPDATE / DO NOTHING) so it is safe to re-run and
 * so a later migration can extend it by regenerating.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const { PERMISSIONS, ROLES, PLANS } = await import("../src/seed-authz.ts");

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];

lines.push("-- Authorization vocabulary. Generated by scripts/generate-authz-migration.mjs.");
lines.push("-- Do not hand-edit: regenerate from packages/db/src/seed-authz.ts.");
lines.push("");

lines.push("INSERT INTO permissions (slug, resource, action, module, description) VALUES");
lines.push(
  PERMISSIONS.map((p) => {
    const i = p.slug.lastIndexOf(".");
    const resource = p.slug.slice(0, i);
    const action = p.slug.slice(i + 1);
    return `  (${q(p.slug)}, ${q(resource)}, ${q(action)}, ${q(p.module)}, ${q(p.description)})`;
  }).join(",\n") +
    "\nON CONFLICT (slug) DO UPDATE SET module = EXCLUDED.module, description = EXCLUDED.description;",
);
lines.push("");

lines.push("INSERT INTO roles (slug, name, description, org_id, rank) VALUES");
lines.push(
  ROLES.map((r) => `  (${q(r.slug)}, ${q(r.name)}, ${q(r.description)}, NULL, ${r.rank})`).join(
    ",\n",
  ) +
    "\nON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description;",
);
lines.push("");

lines.push("INSERT INTO role_permissions (role_slug, permission_slug) VALUES");
lines.push(
  ROLES.flatMap((r) => r.grants.map((g) => `  (${q(r.slug)}, ${q(g)})`)).join(",\n") +
    "\nON CONFLICT DO NOTHING;",
);
lines.push("");

lines.push("INSERT INTO plans (slug, name, rank, is_public, price_monthly, currency) VALUES");
lines.push(
  `${PLANS.map(
    (p) =>
      `  (${q(p.slug)}, ${q(p.name)}, ${p.rank}, true, ${p.priceMonthly === null ? "NULL" : q(p.priceMonthly)}, 'EUR')`,
  ).join(",\n")}\nON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, rank = EXCLUDED.rank;`,
);
lines.push("");

lines.push("INSERT INTO plan_entitlements (plan_slug, key, value) VALUES");
lines.push(
  `${PLANS.flatMap((p) =>
    Object.entries(p.entitlements).map(
      ([k, v]) => `  (${q(p.slug)}, ${q(k)}, ${q(JSON.stringify(v))}::jsonb)`,
    ),
  ).join(",\n")}\nON CONFLICT (plan_slug, key) DO UPDATE SET value = EXCLUDED.value;`,
);
lines.push("");

const sql = lines.join("\n");
const out = join(import.meta.dirname, "..", "drizzle", "0001_seed_authz.sql");
writeFileSync(out, sql);

// drizzle-kit tracks applied migrations in its journal; a hand-added file must
// be registered there or `migrate` will skip it entirely.
const journalPath = join(import.meta.dirname, "..", "drizzle", "meta", "_journal.json");
const journal = JSON.parse(readFileSync(journalPath, "utf8"));
if (!journal.entries.some((e) => e.tag === "0001_seed_authz")) {
  const last = journal.entries[journal.entries.length - 1];
  journal.entries.push({
    idx: (last?.idx ?? -1) + 1,
    version: last?.version ?? "7",
    when: Date.now(),
    tag: "0001_seed_authz",
    breakpoints: true,
  });
  writeFileSync(journalPath, JSON.stringify(journal, null, 2));
}

console.log(
  `wrote ${out} (${PERMISSIONS.length} permissions, ${ROLES.length} roles, ${PLANS.length} plans)`,
);
