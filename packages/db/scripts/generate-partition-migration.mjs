/**
 * Converts `espresso_shots` into a monthly range-partitioned table.
 *
 * drizzle-kit cannot express `PARTITION BY`, so the table it generates in
 * 0000 is an ordinary one. This migration replaces it. That is safe precisely
 * because it runs immediately after creation, while the table is empty — the
 * moment there are rows, converting requires a copy.
 *
 * The column list is derived from the Drizzle definition rather than retyped,
 * and `espresso-shots-partitioning.test.ts` asserts the two agree, so adding a
 * column to the schema without regenerating this fails the build instead of
 * silently producing a table missing it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getTableConfig } from "drizzle-orm/pg-core";

const { espressoShots } = await import("../src/schema/cafe");

const config = getTableConfig(espressoShots);

/** How many months ahead to pre-create. The cron keeps the window rolling. */
const MONTHS_AHEAD = 3;
const MONTHS_BEHIND = 1;

function sqlType(column) {
  const t = column.getSQLType();
  // Drizzle renders enums by name, which is what we want here.
  return t;
}

function columnDdl(column) {
  const parts = [`"${column.name}"`, sqlType(column)];
  if (column.notNull) parts.push("NOT NULL");
  const def = defaultDdl(column);
  if (def) parts.push(`DEFAULT ${def}`);
  return parts.join(" ");
}

/**
 * The SQL default for a column.
 *
 * `defaultRandom()` and `defaultNow()` do not surface as values — Drizzle
 * stores them as SQL objects — so they are mapped by type. Interpolating them
 * as literals is how this file first emitted `DEFAULT '[object Object]'`.
 */
function defaultDdl(column) {
  if (!column.hasDefault) return null;
  const value = column.default;

  if (value === undefined || (typeof value === "object" && value !== null)) {
    const type = column.getSQLType();
    if (type === "uuid") return "gen_random_uuid()";
    if (type.startsWith("timestamp")) return "now()";
    throw new Error(
      `Cannot express the default for "${column.name}" (${type}) as SQL. ` +
        "Add a mapping here rather than emitting a broken migration.",
    );
  }

  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function monthKey(date) {
  return `${date.getUTCFullYear()}_${String(date.getUTCMonth() + 1).padStart(2, "0")}`;
}

function monthBounds(date) {
  const start = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), 1));
  const end = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth() + 1, 1));
  return [start.toISOString().slice(0, 10), end.toISOString().slice(0, 10)];
}

const lines = [];
lines.push("-- espresso_shots: monthly range partitioning.");
lines.push("-- Generated by scripts/generate-partition-migration.mjs. Do not hand-edit.");
lines.push("");
lines.push("DROP TABLE IF EXISTS espresso_shots CASCADE;");
lines.push("");
lines.push("CREATE TABLE espresso_shots (");
lines.push(`${config.columns.map((c) => `  ${columnDdl(c)}`).join(",\n")},`);
// The primary key must contain the partition key, for the same reason the
// dedupe constraint does: Postgres cannot enforce uniqueness across partitions
// without it.
lines.push('  PRIMARY KEY ("id", "pulled_at")');
lines.push(") PARTITION BY RANGE (pulled_at);");
lines.push("");

lines.push("ALTER TABLE espresso_shots");
lines.push('  ADD CONSTRAINT espresso_shots_org_id_organizations_id_fk FOREIGN KEY ("org_id")');
lines.push('    REFERENCES organizations("id") ON DELETE CASCADE;');
lines.push("");

lines.push(
  'CREATE UNIQUE INDEX espresso_shots_dedupe_idx ON espresso_shots ("org_id", "machine_id", "external_id", "pulled_at");',
);
lines.push(
  'CREATE INDEX espresso_shots_site_pulled_idx ON espresso_shots ("org_id", "site_id", "pulled_at");',
);
lines.push(
  'CREATE INDEX espresso_shots_machine_pulled_idx ON espresso_shots ("org_id", "machine_id", "pulled_at");',
);
lines.push(
  'CREATE INDEX espresso_shots_verdict_idx ON espresso_shots ("org_id", "verdict", "pulled_at");',
);
lines.push("");

const now = new Date();
for (let offset = -MONTHS_BEHIND; offset <= MONTHS_AHEAD; offset++) {
  const month = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + offset, 1));
  const [from, to] = monthBounds(month);
  lines.push(
    `CREATE TABLE IF NOT EXISTS espresso_shots_${monthKey(month)} PARTITION OF espresso_shots ` +
      `FOR VALUES FROM ('${from}') TO ('${to}');`,
  );
}
lines.push("");
lines.push("-- A shot that arrives outside every range would otherwise be REJECTED, and a");
lines.push("-- bar bridge with a wrong clock is not a reason to lose data. The cron keeps");
lines.push("-- the rolling window ahead; this catches everything else.");
lines.push(
  "CREATE TABLE IF NOT EXISTS espresso_shots_overflow PARTITION OF espresso_shots DEFAULT;",
);
lines.push("");

const out = join(import.meta.dirname, "..", "drizzle", "0002_partition_shots.sql");
writeFileSync(out, lines.join("\n"));

const journalPath = join(import.meta.dirname, "..", "drizzle", "meta", "_journal.json");
const journal = JSON.parse(readFileSync(journalPath, "utf8"));
if (!journal.entries.some((e) => e.tag === "0002_partition_shots")) {
  const last = journal.entries[journal.entries.length - 1];
  journal.entries.push({
    idx: last.idx + 1,
    version: last.version,
    when: Date.now(),
    tag: "0002_partition_shots",
    breakpoints: true,
  });
  writeFileSync(journalPath, JSON.stringify(journal, null, 2));
}

console.log(
  `wrote ${out} (${config.columns.length} columns, ${MONTHS_BEHIND + MONTHS_AHEAD + 1} partitions)`,
);
